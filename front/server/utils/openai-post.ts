// Скелетон из PR: пост пишется о ходе работы над проектом
export interface IPostDraftPr {
	repoName: string | null;
	projectName: string | null;
	projectDescription: string | null;
	commits: string;
}

export interface IPostDraftInput {
	// для темы — заголовок и excerpt поста, для PR — название и описание PR
	title: string;
	excerpt: string;
	lang: string;
	pr?: IPostDraftPr | null;
}

export interface IPostDraft {
	// для PR модель сама придумывает заголовок и excerpt поста,
	// для темы возвращаются присланные
	title: string;
	excerpt: string;
	// html, при сохранении поста проходит через sanitizePostHtml
	content: string;
	readTime: number;
	// base64 без data:-префикса, как его отдаёт images.generate
	imageBase64: string | null;
}

interface ICoverInput {
	title: string;
	excerpt: string;
}

