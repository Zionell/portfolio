const topicInput = ({ title, excerpt, lang }: IPostDraftInput): string =>
	[`Заголовок: ${title}`, `Описание: ${excerpt}`, `lang: ${lang}`].join("\n");

const prInput = ({ title, excerpt, lang, pr }: IPostDraftInput): string =>
	[
		`Проект: ${pr?.projectName || pr?.repoName || "не указан"}`,
		pr?.repoName ? `Репозиторий: ${pr.repoName}` : "",
		pr?.projectDescription
			? `Описание проекта: ${pr.projectDescription}`
			: "",
		`Название PR: ${title}`,
		`Описание PR: ${excerpt || "—"}`,
		`Коммиты:\n${pr?.commits || "—"}`,
		`lang: ${lang}`,
	]
		.filter(Boolean)
		.join("\n");

const coverPrompt = ({ title, excerpt }: ICoverInput): string =>
	[
		`Cover illustration for a frontend engineering blog post titled "${title}".`,
		// описание PR бывает длинным шаблоном, модели картинок хватает начала
		`Post summary: ${excerpt.slice(0, 500)}`,
		"Style: abstract minimal 3D illustration, dark near-black background, soft green accent glow, subtle depth and grain. One clear visual metaphor for the topic instead of a literal screenshot of code or UI.",
		"Composition: ultra-wide panoramic banner, the subject centered with calm background around it; keep a small margin from the top and bottom edges, they will be slightly cropped.",
		"No text, letters, numbers, logos, watermarks, people or faces.",
	].join("\n");

const createClient = (): OpenAI => {
	const apiKey = process.env.OPENAI_KEY;

	if (!apiKey) {
		throw new Error("OPENAI_KEY должен быть задан");
	}

	return new OpenAI({ apiKey });
};

const parseJson = <T>(text: string): Partial<T> => {
	try {
		return JSON.parse(text);
	} catch {
		throw new Error(`OpenAI вернул не JSON: ${text.slice(0, 200)}`);
	}
};

// Общая часть запросов: свежие факты о версиях и релизах модель берёт
// из веб-поиска, а не из памяти
const WEB_SEARCH_REQUEST = {
	model: DRAFT_TEXT_MODEL,
	service_tier: "default",
	reasoning: { mode: "standard", summary: "auto" },
	tools: [
		{
			type: "web_search",
			user_location: { type: "approximate" },
			search_context_size: "medium",
		},
	],
	store: true,
	include: ["reasoning.encrypted_content", "web_search_call.action.sources"],
} satisfies Partial<OpenAI.Responses.ResponseCreateParamsNonStreaming>;

interface IDraftText {
	title?: string;
	excerpt?: string;
	content: string;
	readTime: number;
}

const requestText = async (
	client: OpenAI,
	input: IPostDraftInput,
): Promise<IDraftText> => {
	const isPr = Boolean(input.pr);

	// в strict-режиме required обязан перечислять все поля
	const properties: Record<string, { type: string }> = {
		...(isPr
			? { title: { type: "string" }, excerpt: { type: "string" } }
			: {}),
		content: { type: "string" },
		readTime: { type: "integer" },
	};

	const response = await client.responses.create({
		...WEB_SEARCH_REQUEST,
		instructions: isPr ? PR_INSTRUCTIONS : DRAFT_INSTRUCTIONS,
		input: isPr ? prInput(input) : topicInput(input),
		text: {
			format: {
				type: "json_schema",
				name: "post_draft",
				strict: true,
				schema: {
					type: "object",
					properties,
					required: Object.keys(properties),
					additionalProperties: false,
				},
			},
		},
	});

	const parsed = parseJson<IDraftText>(response.output_text);

	if (!parsed.content) {
		throw new Error("В ответе OpenAI нет content");
	}

	return {
		title: parsed.title,
		excerpt: parsed.excerpt,
		content: parsed.content,
		readTime: Number(parsed.readTime) || 1,
	};
};

const requestCover = async (
	client: OpenAI,
	input: ICoverInput,
): Promise<string | null> => {
	const image = await client.images.generate({
		model: DRAFT_IMAGE_MODEL,
		prompt: coverPrompt(input),
		size: DRAFT_IMAGE_SIZE,
	});

	return image.data?.[0]?.b64_json || null;
};

const requestPostDraft = async (
	input: IPostDraftInput,
): Promise<IPostDraft> => {
	const client = createClient();

	// Для PR обложку рисуем по придуманным заголовку и excerpt: название
	// PR вроде «feat: update workflow» картинке ничего не говорит
	if (input.pr) {
		const text = await requestText(client, input);
		const title = text.title || input.title;
		const excerpt = text.excerpt || input.excerpt;

		return {
			...text,
			title,
			excerpt,
			imageBase64: await requestCover(client, { title, excerpt }),
		};
	}

	const [text, imageBase64] = await Promise.all([
		requestText(client, input),
		requestCover(client, input),
	]);

	return { ...text, title: input.title, excerpt: input.excerpt, imageBase64 };
};

export function fetchPostDraft(input: IPostDraftInput): Promise<IPostDraft> {
	return isMockEnabled()
		? Promise.resolve(mockPostDraft(input))
		: requestPostDraft(input);
}
